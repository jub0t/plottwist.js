// Builds src/geo/countries.js: world country outlines for IsoRegionMap, from
// Natural Earth 1:110m (public domain) via world-atlas (ISC), with ISO 3166
// codes from i18n-iso-countries (MIT).
//
//   node scripts/build-countries.js [countries-110m.json] [codes.json]
//
// Shared borders stay shared (TopoJSON arcs), coordinates are quantized and
// delta-encoded as signed base-36, so the module stays small and decodes fast.

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const TOPO = 'https://cdn.jsdelivr.net/npm/world-atlas@2/countries-110m.json';
const CODES = 'https://cdn.jsdelivr.net/npm/i18n-iso-countries@7/codes.json';
const load = async (path, url) => JSON.parse(path ? await readFile(path, 'utf8') : await (await fetch(url)).text());

const topo = await load(process.argv[2], TOPO);
const codes = await load(process.argv[3], CODES);

// Natural Earth entries with no ISO numeric code.
const MISSING = { Kosovo: ['XK', 'XKX'], 'N. Cyprus': ['', 'CYN'], Somaliland: ['', 'SOL'] };
const byNumeric = new Map(codes.map(([a2, a3, num]) => [num, [a2, a3]]));

const enc = (n) => (n < 0 ? '-' : '') + Math.abs(n).toString(36);
// Arcs are already quantized and delta-encoded in TopoJSON; keep the integers.
const arcs = topo.arcs.map((arc) => arc.map(([x, y]) => `${enc(x)} ${enc(y)}`).join(',')).join(';');

const countries = topo.objects.countries.geometries
  .filter((g) => g.arcs)
  .map((g) => {
    const name = g.properties.name;
    const [iso2, iso3] = byNumeric.get(g.id) ?? MISSING[name] ?? ['', ''];
    // Polygon -> [rings]; MultiPolygon -> [[rings], ...]; normalise to the latter.
    const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
    return [name, iso2, iso3, g.id ?? '', polys];
  });

const out = `// Generated by scripts/build-countries.js — do not edit by hand.
// Country outlines: Natural Earth 1:110m (public domain) via world-atlas (ISC).
// ISO 3166 codes: i18n-iso-countries (MIT).

export const TRANSFORM = ${JSON.stringify(topo.transform)};
// Quantized, delta-encoded arcs: points "x y" (signed base 36) by ',', arcs by ';'.
export const ARCS = '${arcs}';
// [name, ISO alpha-2, ISO alpha-3, ISO numeric, polygons as arc indexes (~i = reversed)]
export const COUNTRIES = ${JSON.stringify(countries)};
`;
const target = resolve(import.meta.dirname, '../src/geo/countries-data.js');
await writeFile(target, out);
console.log(`wrote ${target}: ${(out.length / 1024).toFixed(1)} KB, ${countries.length} countries`);
const unmatched = countries.filter((c) => !c[2]).map((c) => c[0]);
if (unmatched.length) console.log('no ISO alpha-3:', unmatched.join(', '));
